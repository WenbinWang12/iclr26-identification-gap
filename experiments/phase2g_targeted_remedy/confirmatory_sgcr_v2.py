MEAN_NONINFERIORITY_MARGIN = 0.01


def _verify_lock():
    if not MANIFEST.exists():
        raise RuntimeError(f"missing lock manifest: {MANIFEST}")
    checked = 0
    for raw_line in MANIFEST.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        expected, relative = line.split(maxsplit=1)
        path = ROOT / relative
        actual = hashlib.sha256(path.read_bytes()).hexdigest().upper()
        if actual != expected.upper():
            raise RuntimeError(
                f"lock mismatch for {relative}: expected {expected}, got {actual}"
            )
        checked += 1
    if checked < 9:
        raise RuntimeError("lock manifest is unexpectedly incomplete")
    print(f"lock verification: PASS ({checked} files)")


def _rank(model, tolerance=1e-8):
    singular = np.linalg.svd(model, compute_uv=False)
    if singular[0] == 0.0:
        return 0
    return int(np.sum(singular > tolerance * singular[0]))


def _crossed_gate(tag, difference, threshold):
    iid = _paired_ci(difference)
    crossed = _paired_ci_crossed(
        difference, len(TEACHER_SEEDS), len(STREAM_SEEDS)
    )
    mean, lo, hi, se, components, df = crossed
    passed = bool(lo > threshold)
    print(f"{tag}: {'PASS' if passed else 'FAIL'}")
    print(f"  paired mean {mean:+.4f}; world wins "
          f"{int(np.sum(difference > 0))}/{len(difference)}")
    print(f"  IID 95% CI [{iid[1]:+.4f},{iid[2]:+.4f}] (descriptive)")
    print(f"  crossed 95% CI [{lo:+.4f},{hi:+.4f}], SE={se:.4f}, "
          f"df={df}, threshold={threshold:+.4f}")
    print(f"  variance components={tuple(float(x) for x in components)}")
    return passed


def main():
    _verify_lock()
    cfg = E._cfg()
    if cfg["K"] != 8 or cfg["R"] != 4:
        raise RuntimeError("benchmark configuration differs from locked protocol")
    out = {
        name: {"mean": [], "tail": [], "raw_tail": []}
        for name in ("sgcr2", "q0", "psr", "cvar")
    }
    occupancy = []
    persistent_floats = []
    missing_audit_fallbacks = 0
    final_baseline_selections = 0
    start = time.perf_counter()
    print("LOCKED FRESH CONFIRMATORY PANEL")
    print("teachers:", TEACHER_SEEDS)
    print("streams:", STREAM_SEEDS)
    print("learners:", LEARNER_SEEDS)
    print("method:", METHOD)

    for teacher_seed in TEACHER_SEEDS:
        teacher = E.BM.build_teacher(E.REGIME, cfg, teacher_seed)
        for stream_seed in STREAM_SEEDS:
            windows, frequencies = E.BM.make_stream(cfg, stream_seed)
            batches, sources, _, test = E.BM.materialize(
                teacher, cfg, windows, stream_seed
            )
            per = {name: [] for name in out}
            for learner_seed in LEARNER_SEEDS:
                model, stats = V.run_sgcr_v2(
                    cfg, batches, learner_seed, **METHOD
                )
                q0 = stats["evaluation_frequency_baseline_model"]
                psr = E.P.run_psr_lora(cfg, batches, learner_seed)[0][-1]
                cvar = E.BL.run_excess_cvar(cfg, batches, learner_seed)[0][-1]

                for name, candidate in (
                    ("sgcr2", model), ("q0", q0),
                    ("psr", psr), ("cvar", cvar),
                ):
                    if not np.isfinite(candidate).all():
                        raise RuntimeError(
                            f"non-finite {name} at {teacher_seed}/{stream_seed}/"
                            f"{learner_seed}"
                        )
                    if _rank(candidate) > cfg["R"]:
                        raise RuntimeError(f"rank violation for {name}")
                    per[name].append(
                        E._mean_tail(candidate, sources, frequencies, test)
                    )

                if stats["max_groups"] != 2 * cfg["R"]:
                    raise RuntimeError("K_max is not the locked structural 2R rule")
                if stats["persistent_numeric_floats"] > stats["numeric_budget_floats"]:
                    raise RuntimeError("persistent numeric budget violation")
                occupancy.append(
                    stats["actual_train_entries"]
                    + stats["actual_audit_entries"]
                )
                persistent_floats.append(stats["persistent_numeric_floats"])
                missing_audit_fallbacks += int(
                    stats["selected_candidate"].endswith("missing_audit_support")
                )
                final_baseline_selections += int(stats["selected_round"] == 0)

            for name in out:
                values = np.asarray(per[name])
                out[name]["mean"].append(float(values[:, 0].mean()))
                out[name]["tail"].append(float(values[:, 1].mean()))
                out[name]["raw_tail"].extend(values[:, 1].tolist())
            print(
                f"t{teacher_seed}/s{stream_seed}: "
                f"S {out['sgcr2']['mean'][-1]:.3f}/{out['sgcr2']['tail'][-1]:.3f}  "
                f"Q {out['q0']['mean'][-1]:.3f}/{out['q0']['tail'][-1]:.3f}  "
                f"P {out['psr']['mean'][-1]:.3f}/{out['psr']['tail'][-1]:.3f}  "
                f"C {out['cvar']['mean'][-1]:.3f}/{out['cvar']['tail'][-1]:.3f}",
                flush=True,
            )

    arrays = {}
    print("\n=== summaries: 64 worlds after within-world learner averaging ===")
    for name in out:
        mean = np.asarray(out[name]["mean"])
        tail = np.asarray(out[name]["tail"])
        arrays[name] = mean, tail
        print(f"{name:6s}: mean {mean.mean():.4f} +/- {mean.std():.4f}; "
              f"tail {tail.mean():.4f} +/- {tail.std():.4f}; "
              f"raw learner tail SD {np.std(out[name]['raw_tail']):.4f}")

    sm, st = arrays["sgcr2"]
    _, qt = arrays["q0"]
    pm, pt = arrays["psr"]
    _, ct = arrays["cvar"]
    print("\n=== preregistered primary intersection-union gates ===")
    gate_mean = _crossed_gate(
        "(a) mean non-inferiority SGCR-v2 - PSR",
        sm - pm, -MEAN_NONINFERIORITY_MARGIN
    )
    gate_psr = _crossed_gate(
        "(b) tail superiority SGCR-v2 - PSR", st - pt, 0.0
    )
    gate_cvar = _crossed_gate(
        "(c) tail superiority SGCR-v2 - excess-CVaR", st - ct, 0.0
    )
    print("\n=== preregistered secondary mechanism gate ===")
    gate_q0 = _crossed_gate(
        "(d) tail mechanism SGCR-v2 - same-pool q0", st - qt, 0.0
    )

    total_runs = len(TEACHER_SEEDS) * len(STREAM_SEEDS) * len(LEARNER_SEEDS)
    print("\n=== resource/instrumentation summary ===")
    print(f"occupancy mean/min/max {np.mean(occupancy):.1f}/"
          f"{np.min(occupancy)}/{np.max(occupancy)}")
    print(f"persistent floats mean/max {np.mean(persistent_floats):.1f}/"
          f"{np.max(persistent_floats)}; locked budget {cfg['batch'] * 16 * 2 * cfg['d']}")
    print(f"missing-audit final fallbacks {missing_audit_fallbacks}/{total_runs}")
    print(f"final round-zero selections {final_baseline_selections}/{total_runs}")
    print(f"wall time seconds {time.perf_counter() - start:.1f}")

    primary = gate_mean and gate_psr and gate_cvar
    print("\nPRIMARY VERDICT:",
          "PASS controlled SGCR-v2 result" if primary else "FAIL controlled SGCR-v2 result")
    print("SECONDARY MECHANISM VERDICT:", "PASS" if gate_q0 else "FAIL")
    return 0 if primary else 1


if __name__ == "__main__":
    raise SystemExit(main())
